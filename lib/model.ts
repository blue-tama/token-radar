// The token radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols only. Every slug on the snapshot's watchlist is covered,
// and the early radar adds every pre-token protocol below the watchlist floor that is not a
// wrapped, staked or bridged product of a token that already trades. Protocols whose token
// already trades are never ranked: they are set aside in a separate live list with their market
// caps, which are facts, not a model.
//
// Implied value follows only from the snapshot's own figures, the same function for every row:
//
//   base       = tvl_usd x 0.35
//   growth     = clamp(change_7d, -80, 200) per cent
//   growthMult = 1 + (growth / 100) x 0.75
//   maturity   = 0.5 + min(age_days, 730) / 730 x 0.5   (age_days unknown: 180)
//   implied    = max(1, round(base x growthMult x maturity))
//
// TVL is what the protocol already holds, growth is where it is heading, and age is how long it
// has run with no token on record: a protocol that has held value for two years without issuing
// one has earned a fuller share of its base than one listed last month. No protocol name is ever
// special-cased, and no row is hand-picked.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.35,
  growth_weight: 0.75,
  growth_floor: -80,
  growth_cap: 200,
  maturity_floor: 0.5,
  maturity_range: 0.5,
  maturity_days: 730,
  unknown_age_days: 180,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** A farm step: the action, what it costs, and how long it takes. */
export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

